#pragma once

#include <QColor>
#include <QMap>
#include <QString>
#include <QVariantMap>

// The colours GTK, libadwaita and KDE apps are given for an ambience: the
// highlight tints every background, and all text meets WCAG AA (4.5:1) on
// every background it can be drawn on.
struct ToolkitPalette {
    bool   dark = true;
    QColor accent, accentFg;
    QColor window, view, header, button, tooltip;
    QColor fg, inactiveFg;
    QColor link, visited, negative, neutral, positive;
};

using KdeGroups = QMap<QString, QMap<QString, QString>>;

namespace ToolkitTheme {
    // The first line of every file Marathon writes; a file without it is the
    // user's and is never overwritten.
    inline constexpr char kMarker[] =
        "/* Generated by Marathon from the ambience. Delete this line to keep your own edits. */";

    ToolkitPalette palette(const QColor &highlight, bool dark);
    double         contrast(const QColor &a, const QColor &b);
    // The GNOME 47 named accent libadwaita would pick for this colour.
    QString gnomeAccent(const QColor &color);

    // KDE colour groups (Colors:*, WM) in kdeglobals' encoding, "r,g,b".
    KdeGroups kdeColors(const ToolkitPalette &p);
    QString   kdeColorScheme(const ToolkitPalette &p);
    QString   gtk3Css(const ToolkitPalette &p);
    // libadwaita's named colours for both schemes, the ambience's own first so
    // GTK before 4.20, which has no prefers-color-scheme, still gets it.
    QString gtk4Css(const QColor &highlight, bool dark);
} // namespace ToolkitTheme
