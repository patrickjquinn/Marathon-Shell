//! The user generator: a timer and a service for every declared task.
//!
//! Units are rebuilt on each user-manager start and daemon-reload, so they
//! follow the installed apps and an app cannot ship or edit them itself.

use std::fs;
use std::io;
use std::path::Path;

use crate::check::Network;
use crate::task::{self, Task};

const WANTED_BY: &str = "graphical-session.target.wants";

pub struct Sources<'a> {
    /// `<dir>/<id>/manifest.json`, as `MarathonAppScanner` reads them.
    pub apps: &'a Path,
    /// `<dir>/org.marathonos.<id>.json`, as `install_keel_actions` installs them.
    pub keel_actions: &'a Path,
    /// This binary, for `ExecCondition=`.
    pub helper: &'a Path,
}

pub fn service(task: &Task, helper: &Path, manifest: &Path) -> String {
    let mut lines = vec![
        format!(
            "# Generated by marathon-background-generator from {}.",
            manifest.display()
        ),
        "[Unit]".to_owned(),
        format!("Description={}: background task {}", task.app_name, task.id),
        "PartOf=graphical-session.target".to_owned(),
        "After=graphical-session.target".to_owned(),
    ];
    if task.requires_charging {
        lines.push("ConditionACPower=true".to_owned());
    }
    lines.extend(["", "[Service]", "Type=oneshot", "Slice=background.slice"].map(str::to_owned));
    let mut condition = Vec::new();
    match task.network {
        Some(Network::Any) => condition.push("--network=any"),
        Some(Network::Unmetered) => condition.push("--network=unmetered"),
        None => {}
    }
    if task.requires_battery_not_low {
        condition.push("--battery-not-low");
    }
    if !condition.is_empty() {
        lines.push(format!(
            "ExecCondition={} check {}",
            helper.display(),
            condition.join(" ")
        ));
    }
    // Keel.Actions Invoke: a frozen app has released its name, so the call
    // is bus-activated and marathon-activate has the shell thaw or start it.
    lines.push(format!(
        "ExecStart=busctl --user --timeout={} call org.marathonos.{} \
         /org/shipwright/Keel/Actions org.shipwright.Keel.Actions Invoke ssa{{sv}} {} {{}} 0",
        task.timeout_seconds, task.app_id, task.action
    ));
    lines.push(format!("TimeoutStartSec={}", task.timeout_seconds + 30));
    lines.push(String::new());
    lines.join("\n")
}

pub fn timer(task: &Task, manifest: &Path) -> String {
    format!(
        "# Generated by marathon-background-generator from {}.\n\
         [Unit]\n\
         Description={}: schedule of background task {}\n\
         PartOf=graphical-session.target\n\
         \n\
         [Timer]\n\
         OnCalendar={}\n\
         Persistent=true\n",
        manifest.display(),
        task.app_name,
        task.id,
        task.on_calendar
    )
}

#[allow(
    clippy::print_stderr,
    reason = "generators log to the manager's journal on stderr"
)]
fn log(message: &str) {
    eprintln!("marathon-background-generator: {message}");
}

fn read_tasks(sources: &Sources, app_dir: &Path) -> Option<Vec<Task>> {
    let manifest_path = app_dir.join("manifest.json");
    let manifest = fs::read_to_string(&manifest_path).ok()?;
    let (tasks, refused) = match task::parse(&manifest) {
        Ok(parsed) => parsed,
        Err(e) => {
            if manifest.contains("backgroundTasks") {
                log(&format!("{}: {e}", manifest_path.display()));
            }
            return None;
        }
    };
    for message in refused {
        log(&format!("{}: {message}", manifest_path.display()));
    }
    let app_id = tasks.first().map(|t| t.app_id.clone())?;
    let keel_path = sources
        .keel_actions
        .join(format!("org.marathonos.{app_id}.json"));
    let keel = fs::read_to_string(&keel_path).unwrap_or_default();
    Some(
        tasks
            .into_iter()
            .filter(|t| {
                let declared = task::keel_declares(&keel, &t.action);
                if !declared {
                    log(&format!(
                        "{app_id}: task {:?} names action {:?}, which {} does not declare",
                        t.id,
                        t.action,
                        keel_path.display()
                    ));
                }
                declared
            })
            .collect(),
    )
}

pub fn generate(sources: &Sources, out: &Path) -> io::Result<usize> {
    let Ok(entries) = fs::read_dir(sources.apps) else {
        return Ok(0);
    };
    let mut app_dirs: Vec<_> = entries.filter_map(Result::ok).map(|e| e.path()).collect();
    app_dirs.sort();
    let wants = out.join(WANTED_BY);
    let mut written = 0;
    for app_dir in app_dirs {
        let manifest_path = app_dir.join("manifest.json");
        for task in read_tasks(sources, &app_dir).unwrap_or_default() {
            let stem = task.unit_stem();
            fs::write(
                out.join(format!("{stem}.service")),
                service(&task, sources.helper, &manifest_path),
            )?;
            fs::write(
                out.join(format!("{stem}.timer")),
                timer(&task, &manifest_path),
            )?;
            fs::create_dir_all(&wants)?;
            std::os::unix::fs::symlink(
                format!("../{stem}.timer"),
                wants.join(format!("{stem}.timer")),
            )?;
            written += 1;
        }
    }
    Ok(written)
}

#[cfg(test)]
#[allow(clippy::unwrap_used, reason = "tests")]
mod tests {
    use super::*;

    const KEEL: &str = r#"{"tools": [{"_meta": {"org.shipwright.keel/action": "mail.sync"}}]}"#;

    fn task(json: &str) -> Task {
        let manifest = format!(r#"{{"id": "email", "name": "Mail", "backgroundTasks": [{json}]}}"#);
        task::parse(&manifest).unwrap().0.remove(0)
    }

    #[test]
    fn a_task_without_constraints_just_invokes_its_action() {
        let unit = service(
            &task(r#"{"id": "sync", "action": "mail.sync", "intervalMinutes": 60}"#),
            Path::new("/usr/libexec/marathon-background"),
            Path::new("/usr/share/marathon-apps/email/manifest.json"),
        );
        assert_eq!(
            unit,
            "# Generated by marathon-background-generator from /usr/share/marathon-apps/email/manifest.json.\n\
             [Unit]\n\
             Description=Mail: background task sync\n\
             PartOf=graphical-session.target\n\
             After=graphical-session.target\n\
             \n\
             [Service]\n\
             Type=oneshot\n\
             Slice=background.slice\n\
             ExecStart=busctl --user --timeout=60 call org.marathonos.email \
             /org/shipwright/Keel/Actions org.shipwright.Keel.Actions Invoke ssa{sv} mail.sync {} 0\n\
             TimeoutStartSec=90\n"
        );
    }

    #[test]
    fn constraints_become_conditions() {
        let unit = service(
            &task(
                r#"{"id": "sync", "action": "mail.sync", "intervalMinutes": 60,
                    "network": "unmetered", "requiresCharging": true,
                    "requiresBatteryNotLow": true}"#,
            ),
            Path::new("/usr/libexec/marathon-background"),
            Path::new("m.json"),
        );
        assert!(unit.contains("\nConditionACPower=true\n"), "{unit}");
        assert!(
            unit.contains(
                "\nExecCondition=/usr/libexec/marathon-background check --network=unmetered --battery-not-low\n"
            ),
            "{unit}"
        );
        let any = service(
            &task(r#"{"id": "s", "action": "a", "intervalMinutes": 60, "network": "any"}"#),
            Path::new("/h"),
            Path::new("m.json"),
        );
        assert!(
            any.contains("\nExecCondition=/h check --network=any\n"),
            "{any}"
        );
        assert!(!any.contains("ConditionACPower"));
    }

    #[test]
    fn the_timer_is_a_persistent_calendar_slot() {
        let unit = timer(
            &task(r#"{"id": "sync", "action": "mail.sync", "intervalMinutes": 240}"#),
            Path::new("m.json"),
        );
        assert!(
            unit.contains("\nOnCalendar=00/4:00\nPersistent=true\n"),
            "{unit}"
        );
        assert!(unit.contains("\nPartOf=graphical-session.target\n"));
        assert!(
            !unit.contains("WakeSystem"),
            "the user manager refuses WakeSystem="
        );
    }

    fn install(apps: &Path, keel: &Path, id: &str, manifest: &str, actions: Option<&str>) {
        fs::create_dir_all(apps.join(id)).unwrap();
        fs::write(apps.join(id).join("manifest.json"), manifest).unwrap();
        if let Some(actions) = actions {
            fs::create_dir_all(keel).unwrap();
            fs::write(keel.join(format!("org.marathonos.{id}.json")), actions).unwrap();
        }
    }

    #[test]
    fn units_are_written_for_declared_actions_only() {
        let root = tempfile::tempdir().unwrap();
        let (apps, keel, out) = (
            root.path().join("apps"),
            root.path().join("keel"),
            root.path().join("out"),
        );
        fs::create_dir(&out).unwrap();
        install(
            &apps,
            &keel,
            "email",
            r#"{"id": "email", "name": "Mail", "backgroundTasks": [
                {"id": "sync", "action": "mail.sync", "intervalMinutes": 60, "wake": true},
                {"id": "purge", "action": "mail.purge", "intervalMinutes": 1440}]}"#,
            Some(KEEL),
        );
        install(
            &apps,
            &keel,
            "notes",
            r#"{"id": "notes", "name": "Notes", "backgroundTasks": [
                {"id": "x", "action": "notes.x", "intervalMinutes": 60}]}"#,
            None,
        );
        install(
            &apps,
            &keel,
            "calculator",
            r#"{"id": "calculator", "name": "C"}"#,
            None,
        );
        fs::create_dir_all(apps.join("broken")).unwrap();
        fs::write(apps.join("broken/manifest.json"), "{").unwrap();

        let sources = Sources {
            apps: &apps,
            keel_actions: &keel,
            helper: Path::new("/usr/libexec/marathon-background"),
        };
        assert_eq!(generate(&sources, &out).unwrap(), 1);

        let mut names: Vec<_> = fs::read_dir(&out)
            .unwrap()
            .map(|e| e.unwrap().file_name().into_string().unwrap())
            .collect();
        names.sort();
        assert_eq!(
            names,
            [
                "graphical-session.target.wants",
                "marathon-wake-email.sync.service",
                "marathon-wake-email.sync.timer",
            ]
        );
        let link = out.join("graphical-session.target.wants/marathon-wake-email.sync.timer");
        assert_eq!(
            fs::read_link(&link).unwrap(),
            Path::new("../marathon-wake-email.sync.timer")
        );
        assert!(fs::read_to_string(&link)
            .unwrap()
            .contains("OnCalendar=hourly"));
    }

    #[test]
    fn no_apps_directory_is_no_units() {
        let root = tempfile::tempdir().unwrap();
        let sources = Sources {
            apps: &root.path().join("missing"),
            keel_actions: root.path(),
            helper: Path::new("/h"),
        };
        assert_eq!(generate(&sources, root.path()).unwrap(), 0);
    }
}
