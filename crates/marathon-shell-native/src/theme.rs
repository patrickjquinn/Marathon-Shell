//! The colours GTK, libadwaita and KDE apps are given for an ambience: the
//! highlight tints every background, and all text meets WCAG AA (4.5:1) on
//! every background it can be drawn on. Written to the files GTK reads and
//! served through the Settings portal (portal.rs).

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use palette::color_difference::Wcag21RelativeContrast as _;
use palette::{FromColor, Hsl, Mix, Oklab, Srgb};

/// The first line of every file Marathon writes; a file without it is the
/// user's and is never overwritten.
const MARKER: &str = "/* Generated by Marathon from the ambience. Delete this line to keep your own edits. */";

pub(crate) type Color = Srgb<f32>;

pub(crate) struct Palette {
    pub dark: bool,
    pub accent: Color,
    pub accent_fg: Color,
    pub window: Color,
    pub view: Color,
    pub header: Color,
    pub button: Color,
    pub tooltip: Color,
    pub fg: Color,
    pub inactive_fg: Color,
    pub link: Color,
    pub visited: Color,
    pub negative: Color,
    pub neutral: Color,
    pub positive: Color,
}

fn rgb(r: u8, g: u8, b: u8) -> Color {
    Srgb::new(r, g, b).into_format()
}

/// `#rrggbb`, else none.
pub(crate) fn parse(hex: &str) -> Option<Color> {
    hex.trim().parse::<Srgb<u8>>().ok().map(Srgb::into_format)
}

fn hex(c: Color) -> String {
    format!("#{:x}", c.into_format::<u8>())
}

fn kde(c: Color) -> String {
    let c = c.into_format::<u8>();
    format!("{},{},{}", c.red, c.green, c.blue)
}

fn contrast(a: Color, b: Color) -> f32 {
    a.relative_contrast(b)
}

fn text_on(bg: Color) -> Color {
    let (black, white) = (Srgb::new(0.0, 0.0, 0.0), Srgb::new(1.0, 1.0, 1.0));
    if contrast(bg, black) > contrast(bg, white) { black } else { white }
}

/// Moves a colour's lightness away from the backgrounds until it reads on
/// all of them, keeping its hue.
fn readable(c: Color, backgrounds: &[Color], dark: bool) -> Color {
    let mut hsl = Hsl::from_color(c);
    let worst = |c: Color| backgrounds.iter().map(|bg| contrast(c, *bg)).fold(21.0, f32::min);
    while worst(Srgb::from_color(hsl)) < 4.5 && hsl.lightness > 0.0 && hsl.lightness < 1.0 {
        hsl.lightness = if dark { (hsl.lightness + 0.01).min(1.0) } else { (hsl.lightness - 0.01).max(0.0) };
    }
    Srgb::from_color(hsl)
}

pub(crate) fn palette(highlight: Color, dark: bool) -> Palette {
    let hsl = Hsl::from_color(highlight);
    let tint = (hsl.saturation * 0.35).min(0.22);
    let tone = |lightness: f32, sat: f32| Srgb::from_color(Hsl::new(hsl.hue, tint * sat, lightness));
    let (window, view, header, button, tooltip, fg, inactive) = if dark {
        (tone(0.12, 1.0), tone(0.09, 1.0), tone(0.15, 1.0), tone(0.18, 1.0), tone(0.16, 1.0), tone(0.94, 0.5), tone(0.68, 0.5))
    } else {
        (tone(0.95, 1.0), tone(0.99, 1.0), tone(0.91, 1.0), tone(0.97, 1.0), tone(0.97, 1.0), tone(0.13, 0.6), tone(0.38, 0.5))
    };
    let bgs = [window, view, header, button, tooltip];
    let link = readable(highlight, &bgs, dark);
    Palette {
        dark,
        accent: highlight,
        accent_fg: text_on(highlight),
        window,
        view,
        header,
        button,
        tooltip,
        fg: readable(fg, &bgs, dark),
        inactive_fg: readable(inactive, &bgs, dark),
        link,
        visited: readable(link.mix(rgb(0x9b, 0x59, 0xb6), 0.6), &bgs, dark),
        negative: readable(rgb(0xda, 0x44, 0x53), &bgs, dark),
        neutral: readable(rgb(0xf6, 0x74, 0x00), &bgs, dark),
        positive: readable(rgb(0x27, 0xae, 0x60), &bgs, dark),
    }
}

/// The GNOME 47 named accent libadwaita would pick for this colour
/// (`adw_accent_color_nearest_from_rgba`'s thresholds).
pub(crate) fn gnome_accent(color: Color) -> &'static str {
    let lab = Oklab::from_color(color.into_linear());
    let h = lab.b.atan2(lab.a).to_degrees().rem_euclid(360.0);
    match h {
        _ if lab.a.hypot(lab.b) < 0.04 => "slate",
        h if h > 345.0 => "pink",
        h if h > 280.0 => "purple",
        h if h > 230.0 => "blue",
        h if h > 175.0 => "teal",
        h if h > 115.0 => "green",
        h if h > 75.5 => "yellow",
        h if h > 35.0 => "orange",
        h if h > 10.0 => "red",
        _ => "pink",
    }
}

pub(crate) type Groups = BTreeMap<String, BTreeMap<String, String>>;

fn kde_group(p: &Palette, bg: Color, alt: Color) -> BTreeMap<String, String> {
    [
        ("BackgroundNormal", bg),
        ("BackgroundAlternate", alt),
        ("ForegroundNormal", p.fg),
        ("ForegroundInactive", p.inactive_fg),
        ("ForegroundActive", p.link),
        ("ForegroundLink", p.link),
        ("ForegroundVisited", p.visited),
        ("ForegroundNegative", p.negative),
        ("ForegroundNeutral", p.neutral),
        ("ForegroundPositive", p.positive),
        ("DecorationFocus", p.accent),
        ("DecorationHover", p.accent),
    ]
    .into_iter()
    .map(|(k, c)| (k.to_owned(), kde(c)))
    .collect()
}

/// KDE colour groups (Colors:*, WM) in kdeglobals' encoding, "r,g,b".
pub(crate) fn kde_colors(p: &Palette) -> Groups {
    let mut groups = Groups::new();
    groups.insert("Colors:Window".into(), kde_group(p, p.window, p.header));
    groups.insert("Colors:View".into(), kde_group(p, p.view, p.view.mix(p.fg, 0.05)));
    groups.insert("Colors:Button".into(), kde_group(p, p.button, p.button.mix(p.accent, 0.3)));
    groups.insert("Colors:Header".into(), kde_group(p, p.header, p.window));
    groups.insert("Colors:Tooltip".into(), kde_group(p, p.tooltip, p.window));
    let comp = if p.dark { None } else { Some(palette(p.accent, true)) };
    let c = comp.as_ref().unwrap_or(p);
    groups.insert("Colors:Complementary".into(), kde_group(c, c.window, c.window.mix(c.accent, 0.3)));
    let mut selection = kde_group(p, p.accent, p.accent.mix(p.window, 0.4));
    for (k, v) in &mut selection {
        if k.starts_with("Foreground") {
            *v = kde(p.accent_fg);
        }
    }
    groups.insert("Colors:Selection".into(), selection);
    let wm = [
        ("activeBackground", p.header),
        ("activeForeground", p.fg),
        ("activeBlend", p.fg),
        ("inactiveBackground", p.window),
        ("inactiveForeground", p.inactive_fg),
        ("inactiveBlend", p.inactive_fg),
    ];
    groups.insert("WM".into(), wm.into_iter().map(|(k, c)| (k.to_owned(), kde(c))).collect());
    groups
}

fn adw_colors(p: &Palette, indent: &str) -> String {
    let colors = [
        ("accent_color", p.link),
        ("accent_bg_color", p.accent),
        ("accent_fg_color", p.accent_fg),
        ("destructive_color", p.negative),
        ("destructive_bg_color", p.negative),
        ("destructive_fg_color", text_on(p.negative)),
        ("success_color", p.positive),
        ("warning_color", p.neutral),
        ("error_color", p.negative),
        ("window_bg_color", p.window),
        ("window_fg_color", p.fg),
        ("view_bg_color", p.view),
        ("view_fg_color", p.fg),
        ("headerbar_bg_color", p.header),
        ("headerbar_fg_color", p.fg),
        ("headerbar_backdrop_color", p.window),
        ("sidebar_bg_color", p.header),
        ("sidebar_fg_color", p.fg),
        ("sidebar_backdrop_color", p.window),
        ("secondary_sidebar_bg_color", p.window),
        ("secondary_sidebar_fg_color", p.fg),
        ("card_bg_color", p.button),
        ("card_fg_color", p.fg),
        ("dialog_bg_color", p.header),
        ("dialog_fg_color", p.fg),
        ("popover_bg_color", p.header),
        ("popover_fg_color", p.fg),
        ("thumbnail_bg_color", p.button),
        ("thumbnail_fg_color", p.fg),
    ];
    let mut out = String::new();
    for (name, c) in colors {
        writeln!(out, "{indent}@define-color {name} {};", hex(c)).ok();
    }
    writeln!(out, "{indent}:root {{").ok();
    for (name, c) in colors {
        writeln!(out, "{indent}  --{}: {};", name.replace('_', "-"), hex(c)).ok();
    }
    writeln!(out, "{indent}}}").ok();
    out
}

fn gtk3_css(p: &Palette) -> String {
    let adwaita = if p.dark { "gtk-contained-dark.css" } else { "gtk-contained.css" };
    let border = p.window.mix(p.fg, 0.18);
    let mut css = format!("{MARKER}\n@import url(\"resource:///org/gtk/libgtk/theme/Adwaita/{adwaita}\");\n\n");
    let colors = [
        ("theme_bg_color", p.window),
        ("theme_fg_color", p.fg),
        ("theme_base_color", p.view),
        ("theme_text_color", p.fg),
        ("theme_selected_bg_color", p.accent),
        ("theme_selected_fg_color", p.accent_fg),
        ("insensitive_bg_color", p.window),
        ("insensitive_fg_color", p.inactive_fg),
        ("insensitive_base_color", p.view),
        ("theme_unfocused_bg_color", p.window),
        ("theme_unfocused_fg_color", p.fg),
        ("theme_unfocused_base_color", p.view),
        ("theme_unfocused_text_color", p.fg),
        ("theme_unfocused_selected_bg_color", p.accent),
        ("theme_unfocused_selected_fg_color", p.accent_fg),
        ("borders", border),
        ("unfocused_borders", border),
        ("warning_color", p.neutral),
        ("error_color", p.negative),
        ("success_color", p.positive),
        ("marathon_header_color", p.header),
        ("marathon_button_color", p.button),
        ("marathon_link_color", p.link),
        ("marathon_visited_color", p.visited),
    ];
    for (name, c) in colors {
        writeln!(css, "@define-color {name} {};", hex(c)).ok();
    }
    // Adwaita's GTK 3 stylesheet bakes its colours in, so the widgets that
    // carry most of an app's surface are restyled with the named colours.
    css.push_str(include_str!("theme-gtk3.css"));
    css
}

/// libadwaita's named colours for both schemes, the ambience's own first so
/// GTK before 4.20, which has no prefers-color-scheme, still gets it.
fn gtk4_css(highlight: Color, dark: bool) -> String {
    format!(
        "{MARKER}\n{}\n@media (prefers-color-scheme: dark) {{\n{}}}\n\n@media (prefers-color-scheme: light) {{\n{}}}\n",
        adw_colors(&palette(highlight, dark), ""),
        adw_colors(&palette(highlight, true), "  "),
        adw_colors(&palette(highlight, false), "  ")
    )
}

/// A file Marathon may replace: absent, or one it generated.
fn ours(path: &Path) -> bool {
    std::fs::read_to_string(path).map_or(true, |s| s.lines().next().map(str::trim) == Some(MARKER))
}

fn replace(path: &Path, content: &str) {
    if !ours(path) || std::fs::read_to_string(path).is_ok_and(|s| s == content) {
        return;
    }
    let written = path
        .parent()
        .map_or(Ok(()), std::fs::create_dir_all)
        .and_then(|()| tempfile::NamedTempFile::new_in(path.parent().unwrap_or_else(|| Path::new("/"))))
        .and_then(|mut f| {
            std::io::Write::write_all(&mut f, content.as_bytes())?;
            std::fs::set_permissions(f.path(), std::os::unix::fs::PermissionsExt::from_mode(0o644))?;
            f.persist(path).map(drop).map_err(|e| e.error)
        });
    if let Err(e) = written {
        crate::log::warn("theme", format_args!("cannot write {}: {e}", path.display()));
    }
}

fn gtk4_path() -> PathBuf {
    marathon_rt::dirs::config().join("gtk-4.0/gtk.css")
}

fn gtk3_path(name: &str) -> PathBuf {
    marathon_rt::dirs::data().join(format!("themes/{name}/gtk-3.0/gtk.css"))
}

/// Writes the ambience's GTK styling where GTK reads it: libadwaita's
/// colours to `$XDG_CONFIG_HOME/gtk-4.0` and the GTK 3 "Marathon" themes to
/// `$XDG_DATA_HOME/themes`. Flatpak apps see both through the system
/// override. Whether GTK 3 apps can load "Marathon" and "Marathon-dark".
pub(crate) fn write(highlight: Color, dark: bool) -> bool {
    replace(&gtk4_path(), &gtk4_css(highlight, dark));
    replace(&gtk3_path("Marathon"), &gtk3_css(&palette(highlight, false)));
    replace(&gtk3_path("Marathon-dark"), &gtk3_css(&palette(highlight, true)));
    gtk3_path("Marathon").exists() && gtk3_path("Marathon-dark").exists()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn all_text_meets_aa_on_every_background() {
        for h in ["#7df0d4", "#ff4040", "#808080", "#ffee00", "#2040ff"] {
            for dark in [true, false] {
                let p = palette(parse(h).unwrap_or_default(), dark);
                for bg in [p.window, p.view, p.header, p.button, p.tooltip] {
                    for fg in [p.fg, p.inactive_fg, p.link, p.negative, p.positive] {
                        assert!(contrast(fg, bg) >= 4.5, "{h} dark={dark}");
                    }
                }
            }
        }
    }
}
